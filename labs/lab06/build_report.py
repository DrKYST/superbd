def explain(name):
    """explain/<name>.txt -> (роль, строки результата)."""
    lines = read(EXPL, name + ".txt").splitlines()
    role = next(ln.split(": ", 1)[1] for ln in lines if ln.startswith("Роль: "))
    i = lines.index("-- Результат (первые строки)")
    j = next(k for k in range(i + 1, len(lines)) if lines[k].startswith("-- План"))
    return role, lines[i + 1:j]


