def extract_code(name: str) -> list[str]:
    """Только сам запрос из 060_queries_simple.sql: SELECT представления (без CREATE VIEW)
    или выборка RETURN QUERY функции (без заголовка, объявлений и проверок)."""
    text = SQL.read_text(encoding="utf-8")
    if name.startswith("v_"):
        head = text.index(f"CREATE OR REPLACE VIEW api.{name}")
        start = text.index("SELECT", head)
    else:
        head = text.index(f"CREATE OR REPLACE FUNCTION api.{name}(")
        start = text.index("SELECT", text.index("RETURN QUERY", head))
    end = text.index(";", start) + 1
    # начало строки с SELECT — чтобы общий отступ снялся у всех строк одинаково
    lines = text[text.rindex("\n", 0, start) + 1:end].splitlines()
    lines = [l.partition("--")[0].rstrip() for l in lines if not l.strip().startswith("--")]
    indent = min(len(l) - len(l.lstrip()) for l in lines if l.strip())
    return [l[indent:] for l in lines]


class Builder:
    """Документ на чистом шаблоне ПЗ: тело пустое, элементы строятся из стилей шаблона
    («Заголовок 2–4», «ПЗ Текст», «ПЗ Подпись рисунка», «ПЗ Код», табличный стиль «ПЗ Рамка кода»)."""

    CODE_WIDTH = 9638       # ширина рамки с кодом, twips (17 см — ширина текста при полях шаблона)

    def __init__(self, template: Path):
        self.doc = docx.Document(str(template))
        body = self.doc.element.body
        for el in list(body.iterchildren()):
            if el.tag != qn("w:sectPr"):
                body.remove(el)

    def _paragraph(self, text: str, style: str):
        p = self.doc.add_paragraph(style=style)
        if text:
            p.add_run(text)
        return p

    def heading(self, level: int, text: str):
        self._paragraph(text, f"Heading {level}")
        self.empty()

    def text(self, text: str):
        self._paragraph(text, "ПЗ Текст")

    def empty(self):
        self._paragraph("", "ПЗ Текст")

    def empty_centered(self):
        self._paragraph("", "ПЗ Подпись рисунка")

    def caption(self, text: str):
        self._paragraph(text, "ПЗ Подпись рисунка")

    def code(self, lines: list[str]):
        w = self.CODE_WIDTH
        tbl = parse_xml(
            f'<w:tbl {nsdecls("w")}><w:tblPr><w:tblStyle w:val="PZCodeFrame"/><w:tblW w:w="{w}" w:type="dxa"/>'
            f'<w:jc w:val="center"/><w:tblLayout w:type="fixed"/>'
            f'<w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="1" w:lastColumn="0" '
            f'w:noHBand="0" w:noVBand="1"/></w:tblPr><w:tblGrid><w:gridCol w:w="{w}"/></w:tblGrid>'
            f'<w:tr><w:trPr><w:jc w:val="center"/></w:trPr><w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/></w:tcPr></w:tc>'
            f'</w:tr></w:tbl>')
        self.doc.element.body.find(qn("w:sectPr")).addprevious(tbl)
        cell = Table(tbl, self.doc).rows[0].cells[0]
        for line in lines:
            p = cell.add_paragraph(style="ПЗ Код")
            p.add_run(line.rstrip() or " ")

    def picture(self, path: Path, width_cm: float):
        self._paragraph("", "ПЗ Подпись рисунка").add_run().add_picture(str(path), width=Cm(width_cm))

    def save(self, out: Path):
        cp = self.doc.core_properties
        cp.author = cp.last_modified_by = cp.title = cp.subject = cp.keywords = cp.comments = ""
        out.parent.mkdir(parents=True, exist_ok=True)
        self.doc.save(str(out))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", type=Path, default=ROOT / "tools/md2docx/templates/pz-template.docx")
    ap.add_argument("--section", default="4.7")
    ap.add_argument("--first-figure", type=int, default=1)
    ap.add_argument("-o", "--out", type=Path, default=ROOT / "labs/lab05/out/Запросы_ЛР5.docx")
    args = ap.parse_args()

    b = Builder(args.template)
    sec = args.section
    fig = args.first_figure
    chapter = sec.split(".")[0]
    by_no = {q[0]: q for q in QUERIES}

    b.heading(2, f"{sec} Проектирование запросов")
    b.text("Запросы к базе данных спроектированы как источники данных экранов клиентского приложения: для каждого "
           "запроса определены экран, на котором он используется, роли пользователей и параметры отбора. Запросы без "
           "параметров оформлены представлениями схемы api, запросы с параметрами — функциями этой схемы, которые "
           "выполняются с правами владельца, проверяют группу пользователя и ограничивают строки его провайдером. "
           "Функции, возвращающие списки, принимают размер и смещение страницы и возвращают общее число строк "
           "отбора. Подпункты соответствуют видам запросов: симметричное внутреннее соединение с условием по внешнему "
           "ключу, по датам и без условия, левое и правое внешнее соединение, запрос на запросе по принципу левого "
           "соединения. Для каждого запроса приведены его текст и экран программы с результатом. У запросов, "
           "оформленных функциями, приведена только выборка из тела функции; значения, которые в ней используются, "
           "вычисляются один раз при входе в функцию: имена с префиксом p_ — параметры функции, v_scope — массив "
           "кодов провайдеров, данные которых видит пользователь (свой провайдер или все), v_like — шаблон поиска по "
           "началу строки, v_no_like — тот же шаблон в верхнем регистре для номера договора, v_ip_like — шаблон "
           "поиска по IP-адресу (задан, только если ввод начинается с цифры), v_phone_like — шаблон поиска по "
           "цифрам телефона, v_ip — IP-адрес или подсеть из параметра отбора.")
    b.empty()

    for n3, (title, numbers) in enumerate(SUBSECTIONS, start=1):
        b.heading(3, f"{sec}.{n3} {title}")
        for no in numbers:
            _, obj, name, screen, shot, width, descr = by_no[no]
            code_fig, result_fig = fig, fig + 1
            fig += 2
            b.text(f"{descr} Текст запроса приведён на рисунке {chapter}.{code_fig}, результат на экране программы — "
                   f"на рисунке {chapter}.{result_fig}.")
            b.empty()
            b.code(extract_code(obj))
            b.caption(f"Рисунок {chapter}.{code_fig} – Текст запроса {no} «{name}»")
            b.empty_centered()
            b.picture(SHOTS / shot, width)
            b.caption(f"Рисунок {chapter}.{result_fig} – Результат запроса {no} на экране «{screen}»")
            b.empty()

    b.save(args.out)
    print(f"Готово: {args.out} (рисунки {chapter}.{args.first_figure}–{chapter}.{fig - 1})")


if __name__ == "__main__":
    main()
